/**
 * Generates the language table of `README.md` from the language registries
 * (M1-06), so the README cannot claim support the code does not have.
 *
 * The table is everything between the two marker comments below. One row per
 * entry of `LANGUAGES` (bundled grammars) and `ON_DEMAND_LANGUAGES` (grammars
 * downloaded on first use), in registry order, then one row for the text tier.
 * Tier, extensions and grammar source are read from the entry; only the
 * display name is written here.
 *
 * Run `npx tsx scripts/generate-language-matrix.ts` after adding a language or
 * changing a tier or an extension list; a unit test
 * (`tests/unit/parsers/language-matrix.test.ts`) fails while the committed
 * README is out of date. The script never uses the network.
 */
import { readFileSync, realpathSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { LANGUAGES, type LanguageDefinition } from '../src/parsers/languages.js';
import { ON_DEMAND_LANGUAGES } from '../src/parsers/on-demand-languages.js';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
export const README_FILE = join(ROOT, 'README.md');

export const MATRIX_START = '<!-- hesman:language-matrix:start (generated by scripts/generate-language-matrix.ts; do not edit by hand) -->';
export const MATRIX_END = '<!-- hesman:language-matrix:end -->';

/** How a language is written in prose. A registry id without an entry here fails the generation. */
const DISPLAY_NAMES: Readonly<Record<string, string>> = {
  typescript: 'TypeScript',
  tsx: 'TSX',
  javascript: 'JavaScript (and JSX)',
  python: 'Python',
  go: 'Go',
  java: 'Java',
  c: 'C',
  cpp: 'C++',
  csharp: 'C#',
  rust: 'Rust',
  php: 'PHP',
  ruby: 'Ruby',
  kotlin: 'Kotlin',
  swift: 'Swift',
  bash: 'Bash',
  lua: 'Lua',
  scala: 'Scala',
  ocaml: 'OCaml',
  fsharp: 'F#',
  r: 'R',
  codeql: 'CodeQL',
  arduino: 'Arduino',
};

/** What the tools can answer for a language of this tier. */
const WHAT_WORKS: Readonly<Record<LanguageDefinition['tier'], string>> = {
  deep: 'Symbols, call graph, impact analysis',
  structural: 'Symbols only (no call graph)',
};

const TEXT_ROW =
  '| Everything else | any text file | text | none | Text chunks for `semantic_search`, `find_pattern` and `get_context` (no symbols) |';

function row(def: LanguageDefinition, grammar: 'bundled' | 'on demand'): string {
  const name = DISPLAY_NAMES[def.id];
  if (!name) throw new Error(`No display name for language "${def.id}": add it to DISPLAY_NAMES in scripts/generate-language-matrix.ts`);
  const extensions = def.extensions.map((ext) => `\`${ext}\``).join(', ');
  return `| ${name} | ${extensions} | ${def.tier} | ${grammar} | ${WHAT_WORKS[def.tier]} |`;
}

/** The Markdown table, without the markers and without a trailing newline. */
export function renderLanguageMatrix(): string {
  return [
    '| Language | Extensions | Tier | Grammar | What works |',
    '|---|---|---|---|---|',
    ...LANGUAGES.map((def) => row(def, 'bundled')),
    ...ON_DEMAND_LANGUAGES.map((def) => row(def, 'on demand')),
    TEXT_ROW,
  ].join('\n');
}

/** `readme` with the text between the markers replaced by the current table; everything else is kept. */
export function replaceLanguageMatrix(readme: string): string {
  const start = readme.indexOf(MATRIX_START);
  const end = readme.indexOf(MATRIX_END);
  if (start === -1 || end === -1 || end < start) {
    throw new Error(`README has no "${MATRIX_START}" ... "${MATRIX_END}" block`);
  }
  return `${readme.slice(0, start)}${MATRIX_START}\n${renderLanguageMatrix()}\n${readme.slice(end)}`;
}

function isMainModule(): boolean {
  if (!process.argv[1]) return false;
  try {
    return realpathSync(resolve(process.argv[1])) === realpathSync(fileURLToPath(import.meta.url));
  } catch {
    return false;
  }
}

if (isMainModule()) {
  const before = readFileSync(README_FILE, 'utf-8');
  const after = replaceLanguageMatrix(before);
  if (after === before) {
    console.log(`${README_FILE}: language matrix is up to date.`);
  } else {
    writeFileSync(README_FILE, after);
    console.log(`${README_FILE}: language matrix updated (${LANGUAGES.length} bundled, ${ON_DEMAND_LANGUAGES.length} on demand).`);
  }
}
