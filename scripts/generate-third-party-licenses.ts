/**
 * Generates `THIRD-PARTY-LICENSES.md`: every npm package that is installed
 * together with Hesman (production dependencies, direct and transitive, on
 * every platform), grouped by license.
 *
 * The source is `package-lock.json`, so the result does not depend on the
 * machine or on what happens to be in `node_modules`. Run
 * `npx tsx scripts/generate-third-party-licenses.ts` after changing a
 * dependency; a unit test fails while the committed file is out of date or a
 * package arrives under a license that is not in `ALLOWED_LICENSES`. The
 * script never uses the network.
 */
import { readFileSync, realpathSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
export const LICENSES_FILE = join(ROOT, 'THIRD-PARTY-LICENSES.md');

/**
 * Licenses a production dependency may have. All are permissive and can be
 * combined with Hesman's MIT license. A copyleft or unknown license must not
 * be added here without a decision by the owner.
 */
export const ALLOWED_LICENSES: readonly string[] = [
  'MIT',
  'ISC',
  'Apache-2.0',
  'BSD-2-Clause',
  'BSD-3-Clause',
  '(MIT OR WTFPL)',
  '(BSD-2-Clause OR MIT OR Apache-2.0)',
];

/**
 * Packages whose lockfile entry does not carry an SPDX identifier. Each value
 * was read from the license file the package ships.
 */
export const LICENSE_OVERRIDES: Readonly<Record<string, string>> = {
  // `"license": "SEE LICENSE IN LICENSE.txt"`; LICENSE.txt is the Apache License 2.0.
  flatbuffers: 'Apache-2.0',
};

export interface ThirdPartyPackage {
  name: string;
  version: string;
  license: string;
}

interface LockEntry {
  version?: string;
  license?: string;
  dev?: boolean;
  link?: boolean;
}

/** Production packages of the lockfile, one entry per name and version, sorted. */
export function productionPackages(lockJson: string): ThirdPartyPackage[] {
  const lock = JSON.parse(lockJson) as { packages: Record<string, LockEntry> };
  const found = new Map<string, ThirdPartyPackage>();
  for (const [path, entry] of Object.entries(lock.packages)) {
    if (path === '' || entry.dev === true || entry.link === true || entry.version === undefined) continue;
    const name = path.slice(path.lastIndexOf('node_modules/') + 'node_modules/'.length);
    const license = LICENSE_OVERRIDES[name] ?? entry.license ?? 'UNKNOWN';
    found.set(`${name}@${entry.version}`, { name, version: entry.version, license });
  }
  return [...found.values()].sort(
    (a, b) => a.name.localeCompare(b.name, 'en') || a.version.localeCompare(b.version, 'en'),
  );
}

export function renderThirdPartyLicenses(packages: readonly ThirdPartyPackage[]): string {
  const byLicense = new Map<string, ThirdPartyPackage[]>();
  for (const pkg of packages) {
    const group = byLicense.get(pkg.license) ?? [];
    group.push(pkg);
    byLicense.set(pkg.license, group);
  }
  const licenses = [...byLicense.keys()].sort((a, b) => a.localeCompare(b, 'en'));

  const lines: string[] = [
    '# Third-party licenses',
    '',
    '<!-- Generated by scripts/generate-third-party-licenses.ts from package-lock.json. Do not edit by hand. -->',
    '',
    'Hesman itself is licensed under the MIT License (see [LICENSE](./LICENSE)).',
    '',
    'The npm packages below are **not** part of the Hesman package: npm installs them next to it as',
    'dependencies, each under its own license, and each ships its own license text in its package',
    'directory (`node_modules/<name>/`). The list covers every production dependency, direct and',
    'transitive, on every platform; packages that exist only for another operating system are not',
    'installed on yours.',
    '',
    'Components that are inside the Hesman package (Tree-sitter grammars and queries) and components',
    'downloaded at run time (the embedding model, on-demand grammars) are listed in [NOTICE](./NOTICE).',
    '',
    `${packages.length} packages:`,
    '',
    '| License | Packages |',
    '|---|---:|',
    ...licenses.map((license) => `| ${license} | ${byLicense.get(license)!.length} |`),
    '',
  ];
  for (const license of licenses) {
    lines.push(`## ${license}`, '');
    for (const pkg of byLicense.get(license)!) lines.push(`- ${pkg.name} ${pkg.version}`);
    lines.push('');
  }
  return lines.join('\n');
}

export function generate(): string {
  return renderThirdPartyLicenses(productionPackages(readFileSync(join(ROOT, 'package-lock.json'), 'utf-8')));
}

function isMain(): boolean {
  if (!process.argv[1]) return false;
  try {
    return realpathSync(resolve(process.argv[1])) === realpathSync(fileURLToPath(import.meta.url));
  } catch {
    return false;
  }
}

if (isMain()) {
  writeFileSync(LICENSES_FILE, generate());
  console.log(`Wrote ${LICENSES_FILE}`);
}
